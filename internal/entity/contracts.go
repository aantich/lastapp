package entity

import (
	"fmt"
	"strings"
)

func (d Definition) JSONSchema() any { return d.Schema("record") }
func (d Definition) Schema(mode string) any {
	props := map[string]any{}
	required := []string{}
	for _, f := range d.Fields {
		if mode != "record" && f.Calculation != nil {
			continue
		}
		p := map[string]any{"title": f.Label}
		switch f.Type {
		case "integer":
			p["type"] = "integer"
		case "boolean":
			p["type"] = "boolean"
		case "json":
			p["type"] = []string{"object", "array"}
		default:
			p["type"] = "string"
		}
		if f.Type == "text" {
			p["maxLength"] = f.MaxLength
		}
		if f.Type == "decimal" {
			p["pattern"] = `^-?[0-9]+(\.[0-9]+)?$`
		}
		if f.Type == "choice" {
			p["enum"] = f.Values
			choices := []any{}
			for _, value := range f.Values {
				label := f.ValueLabels[value]
				if label == "" {
					label = value
				}
				choices = append(choices, map[string]any{"const": value, "title": label})
			}
			p["oneOf"] = choices
		}
		if f.Calculation != nil {
			p["readOnly"] = true
		}
		if !f.Required {
			p = map[string]any{"anyOf": []any{p, map[string]any{"type": "null"}}}
		} else {
			if mode == "record" || mode == "create" && f.Default == nil {
				required = append(required, f.Key)
			}
		}
		if mode != "record" && f.Calculation != nil {
			continue
		}
		props[f.Key] = p
	}
	if mode == "record" {
		for _, key := range []string{"created_at", "updated_at", "created_by", "updated_by"} {
			props[key] = map[string]any{"type": "string", "readOnly": true}
		}
		props["id"] = map[string]any{"type": "string", "format": "uuid", "readOnly": true}
		props["revision"] = map[string]any{"type": "integer", "readOnly": true}
		required = append(required, "id", "revision")
	}
	return map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "type": "object", "additionalProperties": false, "properties": props, "required": required}
}

func (d Definition) TypeScript() string {
	var b strings.Builder
	b.WriteString("// Generated by Lastapp. Definition " + Hash(d) + "\nexport interface RecordData {\n  id: string; revision: number;\n  created_at: string; updated_at: string; created_by: string; updated_by: string;\n")
	for _, f := range d.Fields {
		t := "string"
		switch f.Type {
		case "integer":
			t = "number"
		case "boolean":
			t = "boolean"
		case "json":
			t = "Record<string, unknown> | unknown[]"
		case "choice":
			q := []string{}
			for _, v := range f.Values {
				q = append(q, fmt.Sprintf("%q", v))
			}
			t = strings.Join(q, " | ")
		}
		if !f.Required {
			t += " | null"
		}
		fmt.Fprintf(&b, "  %s: %s;\n", f.Key, t)
	}
	b.WriteString("}\nexport interface CreateInput {\n")
	for _, f := range d.Fields {
		if f.Calculation != nil {
			continue
		}
		optional := ""
		if !f.Required || f.Default != nil {
			optional = "?"
		}
		fmt.Fprintf(&b, "  %s%s: RecordData['%s'];\n", f.Key, optional, f.Key)
	}
	b.WriteString("}\nexport type UpdateInput = Partial<CreateInput>;\n")
	return b.String()
}
